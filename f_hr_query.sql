CREATE OR REPLACE FUNCTION F_HR_QUERY RETURN SYS_REFCURSOR IS
v_cur SYS_REFCURSOR;
BEGIN
 OPEN v_cur FOR
 SELECT FIRST_NAME || ' ' || LAST_NAME AS EMPLOYEE_NAME, HIRE_DATE
 FROM MyEmployee
 WHERE HIRE_DATE > (SELECT HIRE_DATE FROM MyEmployee WHERE FIRST_NAME = 'SCOTT')
 ORDER BY HIRE_DATE;
RETURN v_cur;
END;
/

