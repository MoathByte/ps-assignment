#!/bin/bash
echo "System Information"
echo "Executed By: $(whoami)"
echo "Hostname: $(hostname)"
echo "Server IP: $(hostname -I | sed 's/ .*//')"
echo "Public IP: $(curl -s ifconfig.me)"
echo "OS Type and Version: $(lsb_release -ds)"
echo "Kernel Version: $(uname -r)"
echo "Architecture: $(uname -m)"
echo "Virtualization: $(systemd-detect-virt)"
echo "Server Time: $(date)"
echo "Timezone: $(timedatectl | sed -n 's/^ *Time zone: //p')"
echo "Uptime: $(uptime -p | sed 's/up //')"
echo ""
echo "Resource Usage"
echo "Total Memory: $(free -h | grep Mem | sed 's/  */ /g' | cut -d' ' -f2)"
echo "Memory Usage: $(free -h | grep Mem | sed 's/  */ /g' | cut -d' ' -f3) / $(free -h | grep Mem | sed 's/  */ /g' | cut -d' ' -f2)"
echo "Swap Usage: $(free -h | grep Swap | sed 's/  */ /g' | cut -d' ' -f3) / $(free -h | grep Swap | sed 's/  */ /g' | cut -d' ' -f2)"
echo "CPU Cores: $(nproc)"
